"""Deploy one client's instance to a server of its own: an env file in, a working URL out.

    .venv/bin/python tools/deploy_vps.py clients/acme.env

For a client Railway does not suit: a country whose law keeps personal data
at home (Russia), or a business that cannot pay Railway. Any Linux server
with SSH works; Ubuntu 24.04 is what this is tested on. The client rents it in
its own name and adds the installer's SSH key. The env file is the same as for
tools/deploy.py, plus:

    VPS_HOST=root@203.0.113.10         # how to reach the server over SSH
    PUBLIC_URL=https://buy.example.ru  # required: its DNS A record points at the server
    DOCKER_MIRROR=                     # optional: a Docker Hub mirror, where the hub is slow

Every run:

1. Checks the code (a clean git tree), the settings (as production loads
   them) and that the domain already points at the server: without that,
   HTTPS cannot be set up.
2. Fills in what the file lacks and must never change afterwards: SECRET_KEY,
   the VAPID keys and the database password, written back into the file.
3. Installs Docker on the server if it is missing.
4. Uploads exactly the commit (git archive) with the client's own files, and
   the settings to /opt/cash-for-cars/<name>/.env, over SSH's stdin (never on
   a command line).
5. Builds and starts deploy/vps/compose.yaml: the app, PostgreSQL with a
   daily dump, and Caddy for HTTPS.
6. Waits until https://<domain>/healthz reports this commit and the latest
   migration, as tools/deploy.py does.
"""

from __future__ import annotations

import argparse
import io
import ipaddress
import json
import secrets
import shlex
import socket
import subprocess
import sys
import tarfile
import tempfile
from collections.abc import Mapping
from datetime import date
from pathlib import Path
from urllib.parse import urlsplit

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from tools import deploy
from tools.deploy import DeployError, note, step

BASE = "/opt/cash-for-cars"
DAEMON = "/etc/docker/daemon.json"
COMPOSE = "src/deploy/vps/compose.yaml"
# How every command reaches the server. BatchMode: a missing key fails at
# once instead of waiting for a password nobody types. A new server's host
# key is accepted the first time and checked on every run after.
SSH = ["ssh", "-o", "BatchMode=yes", "-o", "StrictHostKeyChecking=accept-new"]

# Set on the server by this script; a value in the file is ignored.
MANAGED = {
    "APP_ENV": "production",
    # Photos in a Docker volume, which outlives every deploy (compose.yaml).
    "STORAGE_BACKEND": "volume",
    # Caddy sets it from the connection itself (deploy/vps/Caddyfile).
    "CLIENT_IP_HEADER": "X-Real-IP",
}


# --- the settings ---------------------------------------------------------------------


def target(env: Mapping[str, str]) -> tuple[str, str]:
    """The SSH destination and the domain, both required."""
    host = env.get("VPS_HOST", "")
    if "@" not in host:
        raise DeployError(
            "VPS_HOST must say how to reach the server, e.g. VPS_HOST=root@203.0.113.10"
        )
    public_url = env.get("PUBLIC_URL", "")
    domain = urlsplit(public_url).hostname or ""
    if not public_url.startswith("https://") or not domain:
        raise DeployError(
            "PUBLIC_URL must be the client's own https:// address, e.g. https://buy.example.ru: "
            "Caddy gets its certificate for that domain."
        )
    return host, domain


def fill_database_password(path: Path, env: dict[str, str]) -> bool:
    if env.get("POSTGRES_PASSWORD"):
        return False
    env["POSTGRES_PASSWORD"] = secrets.token_urlsafe(32)
    deploy.write_env_value(
        path,
        "POSTGRES_PASSWORD",
        env["POSTGRES_PASSWORD"],
        f"Generated by tools/deploy_vps.py on {date.today().isoformat()}. Keep it: the "
        "database on the server was created with it.",
    )
    return True


def server_env(env: Mapping[str, str], sha: str, domain: str) -> dict[str, str]:
    """The settings file the server gets: the app's settings and the compose values."""
    values = {key: value for key, value in deploy.app_values(env).items() if value}
    for key in deploy.CLIENT_FILES.keys() & values.keys():
        values[key] = deploy.uploaded_name(key, values[key])
    for key in deploy.MANAGED:
        values.pop(key, None)
    password = env["POSTGRES_PASSWORD"]
    return {
        **values,
        **MANAGED,
        "DATABASE_URL": f"postgresql://app:{password}@db:5432/app",
        "GIT_SHA": sha,
        # Read by compose.yaml, not by the app.
        "POSTGRES_PASSWORD": password,
        "DOMAIN": domain,
        "BACKUP_DAYS": env.get("BACKUP_DAYS") or "14",
    }


def env_text(values: Mapping[str, str]) -> str:
    # Single quotes: compose takes the value as written, $ and # included.
    lines = []
    for key, value in sorted(values.items()):
        if "'" in value or "\n" in value:
            raise DeployError(f"{key} has a quote or a line break, which the server can't read")
        lines.append(f"{key}='{value}'")
    return "\n".join(lines) + "\n"


# --- the server -------------------------------------------------------------------------


def remote(host: str, command: str, *, stdin: bytes | None = None, check: bool = True) -> str:
    """Run a shell command on the server, as root (sudo for another user)."""
    user = host.split("@", 1)[0]
    wrapped = command if user == "root" else f"sudo sh -c {shlex.quote(command)}"
    result = subprocess.run([*SSH, host, wrapped], input=stdin, capture_output=True, check=False)
    if check and result.returncode != 0:
        output = (result.stderr or result.stdout).decode(errors="replace").strip()
        first = command.strip().splitlines()[0][:80]
        raise DeployError(f"On the server, `{first}` failed: {output[-800:]}")
    return result.stdout.decode(errors="replace")


def check_reachable(host: str) -> None:
    result = subprocess.run([*SSH, "-o", "ConnectTimeout=15", host, "true"], capture_output=True)
    if result.returncode != 0:
        raise DeployError(
            f"Cannot sign in to {host} with an SSH key: "
            f"{result.stderr.decode(errors='replace').strip()}. Add this computer's public key "
            "to the server (docs/deploy-vps.md, Before you start)."
        )


def server_address(host: str) -> str:
    name = host.split("@", 1)[1]
    try:
        return str(ipaddress.ip_address(name))
    except ValueError:
        return socket.gethostbyname(name)


def check_dns(domain: str, address: str) -> None:
    try:
        resolved = {info[4][0] for info in socket.getaddrinfo(domain, 443, socket.AF_INET)}
    except socket.gaierror:
        resolved = set()
    if address not in resolved:
        found = ", ".join(sorted(resolved)) or "nothing"
        raise DeployError(
            f"{domain} points at {found}, not at the server {address}. Add an A record for "
            f"{domain} with the value {address} at the domain's registrar, wait a few "
            "minutes, and run this again: HTTPS can be set up only once the domain points here."
        )


# Ubuntu's own packages first: they come from the distribution's mirrors,
# which are reachable where docker.com may not be. Docker's script otherwise.
INSTALL_DOCKER = """
export DEBIAN_FRONTEND=noninteractive
if ! command -v docker >/dev/null 2>&1; then
  apt-get update -q
  if apt-cache show docker-compose-v2 >/dev/null 2>&1; then
    apt-get install -y -q docker.io docker-compose-v2
  else
    curl -fsSL https://get.docker.com | sh
  fi
fi
if ! docker compose version >/dev/null 2>&1; then
  apt-get update -q
  apt-get install -y -q docker-compose-v2 || apt-get install -y -q docker-compose-plugin
fi
docker compose version
"""


def ensure_docker(host: str, mirror: str) -> None:
    if mirror:
        config = json.dumps({"registry-mirrors": [mirror]})
        remote(
            host,
            f"mkdir -p /etc/docker && printf '%s' {shlex.quote(config)} > {DAEMON}.new && "
            f"if ! cmp -s {DAEMON}.new {DAEMON}; then mv {DAEMON}.new {DAEMON}; "
            f"(systemctl restart docker 2>/dev/null || true); else rm {DAEMON}.new; fi",
        )
        note(f"Docker Hub mirror: {mirror}")
    version = remote(host, INSTALL_DOCKER).strip().splitlines()[-1]
    note(version)


def upload(host: str, env: Mapping[str, str], sha: str, folder: str, settings: str) -> None:
    """The commit and the client's files to src/, the settings to .env."""
    with tempfile.TemporaryDirectory(prefix="deploy-") as staging:
        deploy.stage(env, sha, Path(staging))
        buffer = io.BytesIO()
        with tarfile.open(fileobj=buffer, mode="w:gz") as tar:
            tar.add(staging, arcname=".")
    remote(
        host,
        f"mkdir -p {folder} && rm -rf {folder}/src.new && mkdir {folder}/src.new && "
        f"tar -xzf - -C {folder}/src.new && rm -rf {folder}/src && "
        f"mv {folder}/src.new {folder}/src",
        stdin=buffer.getvalue(),
    )
    remote(
        host,
        f"umask 077 && cat > {folder}/.env.new && mv {folder}/.env.new {folder}/.env",
        stdin=settings.encode(),
    )


def start(host: str, folder: str, name: str) -> None:
    command = (
        f"cd {folder} && docker compose -p {name} --project-directory . -f {COMPOSE} "
        "--env-file .env up -d --build --remove-orphans"
    )
    remote(host, command)


# --- main -----------------------------------------------------------------------------


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("env_file", type=Path, help="the client's settings, e.g. clients/acme.env")
    args = parser.parse_args()
    path: Path = args.env_file

    try:
        step("Checking the code and the settings")
        if not path.is_file():
            raise DeployError(f"{path} does not exist. Copy .env.example and fill it in.")
        sha = deploy.git_sha()
        note(f"commit {sha[:12]}")
        env = deploy.read_env(path)
        host, domain = target(env)
        for key in deploy.fill_secrets(path, env):
            note(f"generated {key} and saved it to {path}")
        if fill_database_password(path, env):
            note(f"generated POSTGRES_PASSWORD and saved it to {path}")
        deploy.validate(env)
        name = deploy.project_name(env)
        folder = f"{BASE}/{name}"
        settings = env_text(server_env(env, sha, domain))
        note("settings, preset and texts are valid for production")

        step(f"Server {host}")
        check_reachable(host)
        address = server_address(host)
        check_dns(domain, address)
        note(f"{domain} points at {address}")
        ensure_docker(host, env.get("DOCKER_MIRROR", ""))

        step(f"Uploading and building commit {sha[:12]}")
        upload(host, env, sha, folder, settings)
        start(host, folder, name)

        step("Waiting for the new code to answer")
        sudo = "" if host.startswith("root@") else "sudo "
        logs = f"ssh {host} '{sudo}docker compose -p {name} logs app'"
        body = deploy.wait_until_live(domain, sha, logs=logs)
    except DeployError as exc:
        print(f"\nDeploy stopped: {exc}", file=sys.stderr)
        raise SystemExit(1) from None

    public = env["PUBLIC_URL"].rstrip("/")
    step("Done")
    note(f"commit {body['version'][:12]}, migration {body['revision']}")
    note(f"seller form:     {public}/")
    note(f"business card:   {public}/v")
    note(f"dashboard:       {public}/app")
    note(f"logs:            {logs}")


if __name__ == "__main__":
    main()
