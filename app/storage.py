"""Photo storage: any S3-compatible bucket in production, a local folder in development.

Both backends store opaque keys generated by the app (never user input), so
a key cannot point outside the bucket or the folder.
"""

from __future__ import annotations

import asyncio
import re
from pathlib import Path
from typing import Protocol

from app.config import Settings

KEY_RE = re.compile(r"^[a-z0-9][a-z0-9/_.-]{0,254}$")


class StorageError(Exception):
    pass


class Storage(Protocol):
    async def put(self, key: str, data: bytes, content_type: str) -> None: ...

    async def get(self, key: str) -> bytes: ...

    async def delete(self, key: str) -> None: ...


def _check_key(key: str) -> str:
    if not KEY_RE.match(key) or ".." in key:
        raise StorageError(f"invalid storage key {key!r}")
    return key


class LocalStorage:
    """Files on disk. Development only: hosting disks are wiped on redeploy."""

    def __init__(self, root: Path) -> None:
        self.root = root

    def _path(self, key: str) -> Path:
        return self.root / _check_key(key)

    async def put(self, key: str, data: bytes, content_type: str) -> None:
        path = self._path(key)
        await asyncio.to_thread(path.parent.mkdir, parents=True, exist_ok=True)
        await asyncio.to_thread(path.write_bytes, data)

    async def get(self, key: str) -> bytes:
        try:
            return await asyncio.to_thread(self._path(key).read_bytes)
        except FileNotFoundError as exc:
            raise StorageError(f"no object {key!r}") from exc

    async def delete(self, key: str) -> None:
        await asyncio.to_thread(self._path(key).unlink, missing_ok=True)


class S3Storage:
    """Any S3-compatible bucket (Railway Buckets, AWS S3, MinIO, ...)."""

    def __init__(self, settings: Settings) -> None:
        import boto3  # imported lazily: development does not need it configured

        self.bucket = settings.s3_bucket
        self.client = boto3.client(
            "s3",
            endpoint_url=settings.s3_endpoint_url or None,
            region_name=settings.s3_region or None,
            aws_access_key_id=settings.s3_access_key_id,
            aws_secret_access_key=settings.s3_secret_access_key,
        )

    async def put(self, key: str, data: bytes, content_type: str) -> None:
        await asyncio.to_thread(
            self.client.put_object,
            Bucket=self.bucket,
            Key=_check_key(key),
            Body=data,
            ContentType=content_type,
        )

    async def get(self, key: str) -> bytes:
        try:
            response = await asyncio.to_thread(
                self.client.get_object, Bucket=self.bucket, Key=_check_key(key)
            )
        except self.client.exceptions.NoSuchKey as exc:
            raise StorageError(f"no object {key!r}") from exc
        return await asyncio.to_thread(response["Body"].read)

    async def delete(self, key: str) -> None:
        await asyncio.to_thread(self.client.delete_object, Bucket=self.bucket, Key=_check_key(key))


def create_storage(settings: Settings) -> Storage:
    if settings.storage_backend == "s3":
        return S3Storage(settings)
    # local and volume differ only in whether the disk outlives a deploy.
    return LocalStorage(settings.local_storage_dir)
